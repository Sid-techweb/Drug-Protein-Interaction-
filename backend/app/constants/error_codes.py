from enum import Enum

class ErrorCode(str, Enum):
    # System & Middleware Errors
    INTERNAL_SERVER_ERROR = "ERR_SYS_500"
    BAD_REQUEST = "ERR_SYS_400"
    UNAUTHORIZED = "ERR_AUTH_401"
    FORBIDDEN = "ERR_AUTH_403"
    NOT_FOUND = "ERR_SYS_404"
    VALIDATION_ERROR = "ERR_VAL_422"

    # Authentication Domain Errors
    INVALID_CREDENTIALS = "ERR_AUTH_INVALID_CREDENTIALS"
    TOKEN_EXPIRED = "ERR_AUTH_TOKEN_EXPIRED"
    INVALID_TOKEN = "ERR_AUTH_INVALID_TOKEN"
    USER_NOT_FOUND = "ERR_AUTH_USER_NOT_FOUND"

    # Platform & Metric Domain Errors
    METRIC_NOT_FOUND = "ERR_METRIC_NOT_FOUND"
    CAPABILITY_NOT_FOUND = "ERR_CAPABILITY_NOT_FOUND"
    WORKFLOW_STAGE_NOT_FOUND = "ERR_WORKFLOW_NOT_FOUND"
    TECH_STACK_NOT_FOUND = "ERR_TECH_STACK_NOT_FOUND"

    # UniProt Integration Errors
    UNIPROT_SERVICE_UNAVAILABLE = "ERR_UNIPROT_UNAVAILABLE"
    PROTEIN_NOT_FOUND = "ERR_PROTEIN_NOT_FOUND"
