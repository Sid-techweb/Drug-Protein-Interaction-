from fastapi import APIRouter, Depends, Header, status
from typing import List
from sqlalchemy.orm import Session
from app.database.connection import get_db
from app.services.auth_service import AuthService
from app.services.report_service import ReportService
from app.schemas.report import ReportGenerateRequest, ScientificReportResponse
from app.exceptions.base_exceptions import AuthenticationException, ResourceNotFoundException

router = APIRouter(prefix="/api/v1/report", tags=["Scientific Report Generator"])

def get_current_user_id(authorization: str = Header(...), db: Session = Depends(get_db)) -> str:
    if not authorization.startswith("Bearer "):
        raise AuthenticationException("Invalid authorization header format.")
    token = authorization.split(" ")[1]
    auth_service = AuthService(db)
    payload = auth_service.decode_token(token)
    return payload.sub

@router.post("/generate", response_model=ScientificReportResponse, status_code=status.HTTP_201_CREATED)
def generate_report(
    request: ReportGenerateRequest,
    user_id: str = Depends(get_current_user_id),
    db: Session = Depends(get_db)
):
    """Assemble scientific report payload from PostgreSQL prediction and quantum records."""
    service = ReportService(db)
    return service.generate_report(
        title=request.title,
        protein_id=request.protein_id,
        user_id=user_id,
        workflow_run_id=request.workflow_run_id
    )

@router.get("/list", response_model=List[ScientificReportResponse])
def get_user_reports(
    user_id: str = Depends(get_current_user_id),
    db: Session = Depends(get_db)
):
    """Retrieve history of scientific reports generated by user."""
    service = ReportService(db)
    return service.report_repo.get_reports_by_user(user_id)

@router.get("/{report_id}", response_model=ScientificReportResponse)
def get_report_details(
    report_id: str,
    user_id: str = Depends(get_current_user_id),
    db: Session = Depends(get_db)
):
    """Retrieve detailed scientific report payload."""
    service = ReportService(db)
    report = service.report_repo.get_report_by_id(report_id)
    if not report:
        raise ResourceNotFoundException("ScientificReport", report_id)
    return report
